export const ordersApi = {
  getOrders: async (): Promise<AdminOrder[]> => {
    try {
      const response = await axiosClient.get('/admin/orders');
      if (response.data && Array.isArray(response.data.data)) {
        return response.data.data;
      }
    } catch {
      // Backend endpoint might not be implemented yet; use mock data
    }
    return MOCK_ADMIN_ORDERS;
  },

  getOrderByCode: async (orderCode: string): Promise<AdminOrder | null> => {
    try {
      const response = await axiosClient.get(`/admin/orders/${orderCode}`);
      if (response.data && response.data.data) {
        return response.data.data;
      }
    } catch {
      // Fallback to mock search
    }
    return MOCK_ADMIN_ORDERS.find((o) => o.orderCode.toLowerCase() === orderCode.toLowerCase()) || null;
  },
};
